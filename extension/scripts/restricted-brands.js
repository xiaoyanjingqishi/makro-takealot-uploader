function checkBlacklistKeywords(title) {
  if (!title) return null;
  const tLower = title.toLowerCase();
  for (const rule of BLACKLIST_RULES) {
    for (const cnW of rule.cn) {
      if (title.includes(cnW)) {
        if (!rule.accessoryExcludes.some(exc => exc.test(tLower))) {
          return `黑名单(${rule.category}: ${cnW})`;
        }
      }
    }
    for (const pat of rule.enPatterns) {
      const m = tLower.match(pat);
      if (m) {
        if (!rule.accessoryExcludes.some(exc => exc.test(tLower))) {
          return `黑名单(${rule.category}: ${m[0]})`;
        }
      }
    }
  }
  return null;
}

function checkTitleForRestrictedBrand(title) {
  if (!title) return null;
  const idx = getRestrictedBrandIndex();
  const normalizedLower = normalizeBrandPunct(title.toLowerCase());
  const lowerTitle = ` ${normalizedLower} `;
  const words = normalizedLower.split(/\s+/);
  const checked = new Set();
  const compatiblePos = lowerTitle.indexOf(' compatible ');
  for (const word of words) {
    if (checked.has(word)) continue;
    checked.add(word);
    const candidates = idx.get(word);
    if (!candidates) continue;
    for (const { original, lower } of candidates) {
      const brandPos = lowerTitle.indexOf(lower);
      if (brandPos === -1) continue;
      if (compatiblePos !== -1 && brandPos > compatiblePos) return null;
      return original;
    }
  }
  return null;
}

function checkTitleRisk(title) {
  if (!title) return null;
  const hitBl = checkBlacklistKeywords(title);
  if (hitBl) return hitBl;
  const hit = checkTitleForRestrictedBrand(title);
  if (hit) return `受限品牌: ${hit}`;
  return null;
}

function detectBrandInScope(scope) {
  if (!scope) scope = document;
  const brandLink = scope.querySelector('a[href^="/all?filter=Brand:"], a[href*="filter=Brand:"]');
  if (brandLink) {
    const brandName = brandLink.textContent?.trim();
    if (brandName && brandName.length > 0) {
      const bLower = brandName.toLowerCase();
      // 只要不是 Generic/白牌，一律判定为有独家商标权的独立品牌 (如 Soulor)
      if (!GENERIC_BRANDS.has(bLower)) {
        return `独立品牌: ${brandName}`;
      }
    }
  }

  let title = '';
  if (scope === document) {
    const tEl = document.querySelector('h1[class*="title"], h1, [class*="product-title"]');
    title = tEl?.textContent?.trim() || '';
  } else {
    const tEl = scope.querySelector('[class*="product-title"], a[href*="PLID"] h2, a[href*="PLID"] h3, h2, h3, a[title]');
    title = tEl?.getAttribute('title') || tEl?.textContent?.trim() || '';
  }
  if (title) {
    const hitRisk = checkTitleRisk(title);
    if (hitRisk) return hitRisk;
  }
  return null;
}

function showBrandConfirmBubble(targetBtn, riskReason) {
  document.querySelectorAll('.tk-brand-bubble').forEach(b => b.remove());
  const bubble = document.createElement('div');
  bubble.className = 'tk-brand-bubble';
  bubble.innerHTML = `⚠️ 检测到风险: <span class="tk-brand-name">${riskReason}</span>，请确认是否采集！`;
  document.body.appendChild(bubble);

  const rect = targetBtn.getBoundingClientRect();
  const bw = bubble.offsetWidth || 300;
  const bh = bubble.offsetHeight || 38;
  let left = rect.left + rect.width / 2 - bw / 2;
  left = Math.max(10, Math.min(left, window.innerWidth - bw - 10));
  const top = Math.max(10, rect.top - bh - 10);
  bubble.style.left = `${left}px`;
  bubble.style.top = `${top}px`;

  requestAnimationFrame(() => bubble.classList.add('show'));
  setTimeout(() => {
    bubble.classList.remove('show');
    setTimeout(() => bubble.remove(), 250);
  }, 6000);
}

function handleBrandConfirmGuard(btn, scope, defaultText) {
  const riskReason = detectBrandInScope(scope);
  if (!riskReason) {
    delete btn.dataset.brandConfirmed;
    return false;
  }
  if (btn.dataset.brandConfirmed === '1') {
    delete btn.dataset.brandConfirmed;
    if (btn._brandConfirmTimer) { clearTimeout(btn._brandConfirmTimer); btn._brandConfirmTimer = null; }
    btn.classList.remove('warning');
    return false;
  }
  btn.dataset.brandConfirmed = '1';
  btn.innerHTML = '⚠️ 确认采集';
  btn.classList.add('warning');
  showBrandConfirmBubble(btn, riskReason);

  if (btn._brandConfirmTimer) clearTimeout(btn._brandConfirmTimer);
  btn._brandConfirmTimer = setTimeout(() => {
    if (btn.dataset.brandConfirmed === '1') {
      delete btn.dataset.brandConfirmed;
      btn.innerHTML = defaultText;
      btn.classList.remove('warning');
    }
    btn._brandConfirmTimer = null;
  }, 10000);
  return true;
}

window.TkBrandChecker = {
  checkTitle: checkTitleRisk,
  checkTitleForRestrictedBrand: checkTitleForRestrictedBrand,
  checkBlacklistKeywords: checkBlacklistKeywords,
  detectInScope: detectBrandInScope,
  showBubble: showBrandConfirmBubble,
  guard: handleBrandConfirmGuard
};
