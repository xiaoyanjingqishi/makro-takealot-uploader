function normalizeBrandPunct(s) {
  if (!s) return '';
  return s.replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
}

let _restrictedBrandIndex = null;
function getRestrictedBrandIndex() {
  if (_restrictedBrandIndex) return _restrictedBrandIndex;
  const list = (typeof window !== 'undefined' && Array.isArray(window.__HG_RESTRICTED_BRANDS))
    ? window.__HG_RESTRICTED_BRANDS
    : [];
  _restrictedBrandIndex = new Map();
  for (const brand of list) {
    const lower = normalizeBrandPunct(brand.toLowerCase());
    if (!lower) continue;
    const firstWord = lower.split(/\s+/)[0];
    let bucket = _restrictedBrandIndex.get(firstWord);
    if (!bucket) { bucket = []; _restrictedBrandIndex.set(firstWord, bucket); }
    bucket.push({ original: brand, lower: ` ${lower} ` });
  }
  for (const bucket of _restrictedBrandIndex.values()) {
    bucket.sort((a, b) => b.lower.length - a.lower.length);
  }
  return _restrictedBrandIndex;
}

